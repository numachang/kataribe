/** 新規作成した直後の作品。設定資料は何も生成されていない。 */
export function createEmptyProjectState(folder: string, project: NewProject): ProjectState {
  const manifest: Manifest = {
    format: MANIFEST_FORMAT,
    title: project.title,
    author: project.author,
    genre: project.genre,
    genre_note: project.genre_note,
    rating: project.rating,
    target_length: project.target_length,
    idea: project.idea,
  };
  return {
    folder,
    manifest,
    concept: null,
    style: null,
    world: null,
    characters: null,
    synopsis: null,
    chapters: null,
  };
}

